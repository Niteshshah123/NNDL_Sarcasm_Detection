"""## Dynamic token-pruning model

The model below uses the **first `SCORER_LAYERS` DistilBERT layers** to build contextual token representations.

A small learned scorer produces one scalar score per token:

`token representation → Linear → GELU → Linear → relevance score`

For each example, the model keeps the highest-scoring valid tokens while always retaining `[CLS]` and `[SEP]`.

The remaining DistilBERT layers then process only the selected sequence.

This makes the selector part of the neural network rather than using a separate pretrained model to decide which words are important.

"""

# =========================
# CELL 12 — Dynamic Token Pruning model
# =========================
class DynamicPrunedDistilBERT(nn.Module):
    def __init__(
        self,
        model_name=MODEL_NAME,
        keep_ratio=KEEP_RATIO,
        scorer_layers=SCORER_LAYERS
    ):
        super().__init__()

        self.encoder = AutoModel.from_pretrained(model_name)
        self.keep_ratio = keep_ratio
        self.scorer_layers = scorer_layers

        # DistilBERT internals
        self.embeddings = self.encoder.embeddings
        self.transformer_layers = self.encoder.transformer.layer
        self.pre_classifier = self.encoder.config.hidden_size

        hidden = self.encoder.config.hidden_size

        # Lightweight learned token scorer
        self.token_scorer = nn.Sequential(
            nn.Linear(hidden, 128),
            nn.GELU(),
            nn.Linear(128, 1)
        )

        self.dropout = nn.Dropout(0.2)
        self.classifier = nn.Linear(hidden, 2)

    def run_layer(self, layer, hidden_states, attention_mask):
        # DistilBERT layer expects attention mask with shape [B, 1, 1, L]
        extended_mask = attention_mask[:, None, None, :]
        return layer(
            hidden_states,
            attn_mask=extended_mask
        )

    def forward(self, input_ids, attention_mask, labels=None, return_selection=False):

        # Embedding
        hidden_states = self.embeddings(input_ids)

        # First few layers: full sequence
        for i in range(self.scorer_layers):
            hidden_states = self.run_layer(
                self.transformer_layers[i],
                hidden_states,
                attention_mask
            )

        # Score each token
        scores = self.token_scorer(hidden_states).squeeze(-1)

        batch_size, seq_len = input_ids.shape

        cls_id = tokenizer.cls_token_id
        sep_id = tokenizer.sep_token_id

        # Valid candidate positions:
        # - attention_mask == 1
        # - not CLS
        # - not SEP
        candidate_mask = attention_mask.bool()
        candidate_mask &= (input_ids != cls_id)
        candidate_mask &= (input_ids != sep_id)

        # Number of content tokens to retain.
        valid_counts = candidate_mask.sum(dim=1)

        k_list = torch.clamp(
            torch.ceil(valid_counts.float() * self.keep_ratio).long(),
            min=1
        )

        # For batching, use the maximum k in this batch.
        max_k = int(k_list.max().item())

        # Never exceed available content positions.
        max_k = min(max_k, seq_len - 2)

        masked_scores = scores.masked_fill(~candidate_mask, -1e9)

        topk_idx = torch.topk(
            masked_scores,
            k=max_k,
            dim=1
        ).indices

        # Keep original token order after selecting by score.
        topk_idx, _ = torch.sort(topk_idx, dim=1)

        # Add CLS at beginning and SEP at end.
        cls_positions = torch.zeros(
            (batch_size, 1), dtype=torch.long, device=input_ids.device
        )

        # Gather original SEP position for every sample.
        sep_positions = attention_mask.sum(dim=1) - 1
        sep_positions = sep_positions.clamp(min=1).unsqueeze(1)

        selected_positions = torch.cat(
            [cls_positions, topk_idx, sep_positions],
            dim=1
        )

        # Gather selected hidden states.
        gather_idx = selected_positions.unsqueeze(-1).expand(
            -1, -1, hidden_states.size(-1)
        )

        pruned_hidden = torch.gather(
            hidden_states,
            dim=1,
            index=gather_idx
        )

        pruned_mask = torch.ones(
            (batch_size, selected_positions.size(1)),
            dtype=attention_mask.dtype,
            device=attention_mask.device
        )

        # Remaining layers
        for i in range(self.scorer_layers, len(self.transformer_layers)):
            pruned_hidden = self.run_layer(
                self.transformer_layers[i],
                pruned_hidden,
                pruned_mask
            )

        cls = pruned_hidden[:, 0, :]
        logits = self.classifier(self.dropout(cls))

        loss = None
        if labels is not None:
            loss = nn.CrossEntropyLoss()(logits, labels)

        if return_selection:
            return logits, loss, {
                "selected_positions": selected_positions,
                "scores": scores,
                "candidate_mask": candidate_mask,
                "k_list": k_list,
                "original_lengths": valid_counts,
                "selected_length": selected_positions.size(1)
            }

        return logits, loss


