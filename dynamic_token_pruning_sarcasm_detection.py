def show_token_selection(texts, keep_ratio=KEEP_RATIO, n=10):
    enc = tokenizer(
        list(texts[:n]),
        padding="max_length",
        truncation=True,
        max_length=MAX_LEN,
        return_tensors="pt"
    )

    labels = torch.zeros(len(texts[:n]), dtype=torch.long)

