    pruned_model.eval()
    with torch.no_grad():
        _, _, info = pruned_model(
            enc["input_ids"],
            enc["attention_mask"],
            return_selection=True
        )

    for i in range(len(texts[:n])):
        original_tokens = tokenizer.convert_ids_to_tokens(
            enc["input_ids"][i].cpu().tolist()
        )

        selected_positions = info["selected_positions"][i].cpu().tolist()

        selected_tokens = [
            original_tokens[p]
            for p in selected_positions
        ]

        # Remove padding from original display
        original_tokens_clean = [
            t for t in original_tokens
            if t not in ["[PAD]"]
        ]

        print("=" * 80)
        print("ORIGINAL:")
        print(tokenizer.convert_tokens_to_string(original_tokens_clean))
        print("\nSELECTED:")
        print(tokenizer.convert_tokens_to_string(selected_tokens))
        print("\nSELECTED TOKEN POSITIONS:", selected_positions)

